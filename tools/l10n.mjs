const here = path.dirname(fileURLToPath(import.meta.url));
const res = path.join(here, '..', 'Resources');
const quote = s => '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
const specs = s => (s.match(/%(@|lld)/g) || []).join(',');

const seen = new Set();
for (const row of strings) {
  if (row.length !== languages.length + 1) throw new Error('wrong number of languages: ' + row[0]);
  if (seen.has(row[0])) throw new Error('twice: ' + row[0]);
  seen.add(row[0]);
  for (const t of row.slice(1)) if (specs(t) !== specs(row[0])) throw new Error(`placeholders differ: ${row[0]} → ${t}`);
}

for (const [i, lang] of ['it', ...languages].entries()) {
  const dir = path.join(res, `${lang}.lproj`);
  fs.mkdirSync(dir, { recursive: true });
  const header = `/* TrackLap, ${lang}. Generated by tools/l10n.mjs: edit the table there. */\n\n`;
  const body = strings.map(r => `${quote(r[0])} = ${quote(r[i] ?? r[0])};`).join('\n');
  fs.writeFileSync(path.join(dir, 'Localizable.strings'), header + body + '\n');
  const info = Object.entries(infoPlist).map(([k, v]) => `${k} = ${quote(v[i])};`).join('\n');
  fs.writeFileSync(path.join(dir, 'InfoPlist.strings'), header + info + '\n');
}
